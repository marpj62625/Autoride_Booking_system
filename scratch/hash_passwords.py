def replace_once(s, old, new, label):
    if old not in s:
        print(f"  WARN [{label}]: pattern not found")
        return s
    count = s.count(old)
    if count > 1:
        print(f"  WARN [{label}]: pattern found {count} times, replacing first only")
    return s.replace(old, new, 1)


