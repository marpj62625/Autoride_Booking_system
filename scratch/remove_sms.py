# ?? 1g. Remove all sms_service.notify_customer / sms_service.notify_admins / sms_service.notify_phone calls
#        including the multiline versions (indented blocks with blank lines between)
# Strategy: remove entire sms_service.* statement blocks (may span multiple lines due to blank line formatting)

def remove_sms_service_calls(text):
    """Remove sms_service.notify_* calls and the associated sms_msg = compose_*() lines."""
    lines = text.split('\n')
    result = []
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Skip sms_msg = compose_... lines
        if re.match(r'sms_msg\s*=\s*compose_', stripped):
            # consume continuation lines (closing paren)
            while i < len(lines) and ')' not in lines[i]:
                i += 1
            i += 1  # skip the closing paren line too
            continue

        # Skip sms_service.notify_* lines (and their multiline continuations)
        if re.match(r'sms_service\.(notify_customer|notify_admins|notify_phone)', stripped):
            # consume until closing paren
            while i < len(lines) and ')' not in lines[i]:
                i += 1
            i += 1  # skip the closing paren line
            continue

        result.append(line)
        i += 1

    return '\n'.join(result)

