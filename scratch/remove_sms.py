def clean_html(text):
    # Remove phone-login link wrapper div
    text = re.sub(
        r'\s*<div class="auth-link" style="margin-top:12px;">\s*<a href="#" onclick="showPage\(\'page-phone-login\'\)"[^<]*</a>\s*</div>',
        '',
        text
    )

    # Remove the entire page-phone-login div block
    # It starts with <!-- PHONE LOGIN ... --> then <div id="page-phone-login" ...> and ends with a </div>
    text = re.sub(
        r'<!--\s*PHONE LOGIN.*?-->\s*<div id="page-phone-login".*?</div>\s*</div>\s*</div>',
        '',
        text,
        flags=re.DOTALL
    )

    # Remove SMS notifications toggle block
    text = re.sub(
        r'\s*<div class="more-item" style="cursor:default;">\s*<div class="more-item-icon"><i class="fas fa-sms"></i></div>.*?</div>\s*</div>',
        '',
        text,
        flags=re.DOTALL
    )

    return text

