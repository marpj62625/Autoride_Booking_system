def clean_js(text):
    # Remove pendingOtpPhone variable
    text = re.sub(r"\s*var pendingOtpPhone\s*=\s*'';", '', text)

    # Remove || activeAuth.id === 'page-phone-login' from back-button check
    text = re.sub(r"\s*\|\|\s*activeAuth\.id\s*===\s*'page-phone-login'", '', text)

    # Remove otpNextSms function
    text = re.sub(
        r'\s*function otpNextSms\(el,\s*nextIdx\)\s*\{[^}]*\}',
        '',
        text,
        flags=re.DOTALL
    )

    # Remove doRequestOtp function
    text = re.sub(
        r'\s*function doRequestOtp\(\)\s*\{.*?(?=\n\s*function |\n\s*var |\nfunction )',
        '',
        text,
        flags=re.DOTALL
    )

    # Remove doVerifyPhone function
    text = re.sub(
        r'\s*function doVerifyPhone\(\)\s*\{.*?(?=\n\s*function |\n\s*var |\nfunction )',
        '',
        text,
        flags=re.DOTALL
    )

    # Remove SMS preference loading block inside loadMorePage
    text = re.sub(
        r"\s*// ?[Ll]oad SMS.*?toggleSmsOptOut.*?\}\s*\}\s*\);",
        '',
        text,
        flags=re.DOTALL
    )

    # Remove apiCall block that loads sms_opt_out
    text = re.sub(
        r"\s*apiCall\('/user/profile-full\?.*?sms_opt_out.*?\}\s*\}\s*\);",
        '',
        text,
        flags=re.DOTALL
    )

    # Remove toggleSmsOptOut function
    text = re.sub(
        r'\s*function toggleSmsOptOut\(checkbox\)\s*\{.*?(?=\n\s*function |\n\s*var |\nfunction )',
        '',
        text,
        flags=re.DOTALL
    )

    return text

